/* sync_docs.js -- mirror the browser modules the Pages demo needs into docs/js/.
 *
 * GitHub Pages serves only /docs, so docs/hybrid_tsp.html cannot load ../src.
 * The canonical sources stay in src/ (the Node CLI and the benchmarks import
 * them there); this script copies the two browser-only modules the page loads,
 * with a generated-file banner so nobody edits the copy by mistake.
 *
 *   node bench/sync_docs.js          # copy
 *   node bench/sync_docs.js --check   # exit 1 if docs/js is out of date
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const PAIRS = [
  ['src/hybrid/effort_profiles.js', 'docs/js/effort_profiles.js'],
  ['src/hybrid/hybrid_vis.js', 'docs/js/hybrid_vis.js'],
  ['src/farthest/farthest_pole.js', 'docs/js/farthest_pole.js']
];

function banner(from) {
  return '/* generated by bench/sync_docs.js from ' + from + ' -- do not edit */\n';
}

function expected(from) {
  return banner(from) + fs.readFileSync(path.join(ROOT, from), 'utf8');
}

function fingerprint(text) {
  return require('crypto').createHash('sha1').update(text).digest('hex').slice(0, 8);
}

const check = process.argv.includes('--check');
let stale = 0;

for (const [from, to] of PAIRS) {
  const dest = path.join(ROOT, to);
  const want = expected(from);
  const have = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : null;

  if (have === want) {
    console.log('ok      ' + to);
    continue;
  }
  if (check) {
    console.log('stale   ' + to + '  (source ' + from + ' is ' + fingerprint(want) + ')');
    stale++;
    continue;
  }
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, want);
  console.log('updated ' + to);
}

if (check) {
  if (stale) {
    console.error('\n' + stale + ' file(s) out of date -- run: node bench/sync_docs.js');
    process.exit(1);
  }
  console.log('\ndocs/js is in sync with src/');
}
